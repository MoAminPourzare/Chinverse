export function isKnownProfileHeadline(value?: string | null) {
    if (!value) return false;
    return PROFILE_HEADLINE_OPTIONS.includes(value.trim());
}

export function isKnownCountry(value?: string | null) {
    if (!value) return false;
    return COUNTRY_REGION_OPTIONS.includes(value.trim());
}

export function isKnownIranProvince(value?: string | null) {
    if (!value) return false;
    return IRAN_PROVINCE_OPTIONS.includes(value.trim());
}

export function getProvinceOptions(country?: string | null) {
    if (!country) return [];
    return PROVINCES_BY_COUNTRY_REGION[country.trim()] || [];
}

export function requiresProvince(country?: string | null) {
    return getProvinceOptions(country).length > 0;
}

export function isKnownProvinceForCountry(country?: string | null, province?: string | null) {
    if (!province) return false;
    return getProvinceOptions(country).includes(province.trim());
}
